CREATE TABLE rol (
    id_rol integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(30) NOT NULL,
    nombre varchar(80) NOT NULL,
    CONSTRAINT uq_rol_codigo UNIQUE (codigo),
    CONSTRAINT ck_rol_codigo CHECK (codigo IN ('DONANTE', 'ENFERMERIA', 'JEFATURA', 'ADMIN'))
);

CREATE TABLE tipo_sangre (
    id_tipo_sangre integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo char(2) NOT NULL,
    factor char(1) NOT NULL,
    CONSTRAINT uq_tipo_sangre_grupo_factor UNIQUE (grupo, factor),
    CONSTRAINT ck_tipo_sangre_grupo CHECK (grupo IN ('A', 'B', 'AB', 'O')),
    CONSTRAINT ck_tipo_sangre_factor CHECK (factor IN ('+', '-'))
);

CREATE TABLE usuario (
    id_usuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento varchar(20) NOT NULL,
    nombre varchar(80) NOT NULL,
    apellido varchar(80) NOT NULL,
    fecha_nacimiento date NOT NULL,
    genero varchar(20) NOT NULL,
    contrasena varchar(255),
    consentimiento_privacidad boolean NOT NULL,
    estado boolean NOT NULL DEFAULT true,
    cuenta_suprimida boolean NOT NULL DEFAULT false,
    fecha_alta timestamp NOT NULL,
    id_tipo_sangre integer,
    CONSTRAINT uq_usuario_documento UNIQUE (documento),
    CONSTRAINT ck_usuario_genero CHECK (genero IN ('Masculino', 'Femenino')),
    CONSTRAINT ck_usuario_supresion CHECK (cuenta_suprimida = false OR contrasena IS NULL),
    CONSTRAINT fk_usuario_tipo_sangre FOREIGN KEY (id_tipo_sangre) REFERENCES tipo_sangre (id_tipo_sangre)
);

CREATE TABLE usuario_rol (
    id_usuario integer NOT NULL,
    id_rol integer NOT NULL,
    CONSTRAINT pk_usuario_rol PRIMARY KEY (id_usuario, id_rol),
    CONSTRAINT fk_usuario_rol_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_usuario_rol_rol FOREIGN KEY (id_rol) REFERENCES rol (id_rol)
);

