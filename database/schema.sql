-- fecha_fin = fecha_inicio + dias_rehabilitacion; nula si el diferimiento es permanente.
CREATE FUNCTION fn_registro_fecha_fin()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_tipo varchar(20);
    v_dias integer;
BEGIN
    SELECT tipo, dias_rehabilitacion
    INTO v_tipo, v_dias
    FROM diferimiento
    WHERE id_diferimiento = NEW.id_diferimiento;

    IF NOT FOUND THEN
        RETURN NEW;
    END IF;

    IF v_tipo = 'Permanente' THEN
        NEW.fecha_fin := NULL;
    ELSIF NEW.fecha_fin IS NULL AND v_dias IS NOT NULL THEN
        NEW.fecha_fin := NEW.fecha_inicio + v_dias;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_registro_fecha_fin
BEFORE INSERT OR UPDATE ON registro_diferimiento
FOR EACH ROW
EXECUTE FUNCTION fn_registro_fecha_fin();

