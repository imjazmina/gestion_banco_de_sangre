-- RN01: apto se calcula con los umbrales del tipo. El personal no lo edita.
CREATE FUNCTION fn_medicion_apto()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_min numeric;
    v_max numeric;
BEGIN
    SELECT valor_minimo, valor_maximo
    INTO v_min, v_max
    FROM tipo_medicion
    WHERE id_tipo_medicion = NEW.id_tipo_medicion;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Tipo de medicion inexistente';
    END IF;

    NEW.apto := NEW.valor >= v_min AND NEW.valor <= v_max;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_medicion_apto
BEFORE INSERT OR UPDATE ON medicion
FOR EACH ROW
EXECUTE FUNCTION fn_medicion_apto();

-- RN02: nadie se valida a si mismo.
CREATE FUNCTION fn_medicion_no_autovalida()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM cita
        WHERE id_cita = NEW.id_cita
          AND id_usuario = NEW.id_personal
    ) THEN
        RAISE EXCEPTION 'El personal no puede validar su propia donacion';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_medicion_no_autovalida
BEFORE INSERT OR UPDATE ON medicion
FOR EACH ROW
EXECUTE FUNCTION fn_medicion_no_autovalida();

CREATE FUNCTION fn_cuestionario_no_autovalida()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_parte char(1);
BEGIN
    SELECT parte
    INTO v_parte
    FROM pregunta
    WHERE id_pregunta = NEW.id_pregunta;

    IF v_parte = 'B'
       AND NEW.id_personal IS NOT NULL
       AND NEW.id_personal = NEW.id_donante THEN
        RAISE EXCEPTION 'El personal no puede validar su propia donacion';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_cuestionario_no_autovalida
BEFORE INSERT OR UPDATE ON cuestionario
